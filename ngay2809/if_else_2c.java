package ngay2809;

public class if_else_2c {
    public static void main(String[] arga) {
        int x = 1500;
        int y = 300;
        if (x < 2000 || x > 3000) {
            System.out.println("x = " + x);
        }
        if (y >= 100 && y <= 500) {
            System.out.println("y = " + y);
        }
    }
}
