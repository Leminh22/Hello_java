package sli22;

public class EscapeSequence {
    public static void main(String[] args) {
        // Sử dụng chuỗi thoát tab và xuống dòng 
        System.out.println("Hello\tWorld!"); // In ra "Hello    World!" với tab\
        // In ra chuỗi Hello "Dick" World
        System.out.println("Hello \"Dick\" World");

    }
}
