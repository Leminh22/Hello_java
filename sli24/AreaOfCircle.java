package sli24;

public class AreaOfCircle {
    public static void main(String[] args) {
        // Khai báo biến hằng số 
        final double PI = 3.14159;// Khai báo biến bán kính hình tròn 
        double radius = 5.87;
        double area;
        // Tính toán biến cho giá trị diện tích 
        area = PI * radius * radius;
        System.out.println("Diện tích hình tròn là" + area);
    }


}
